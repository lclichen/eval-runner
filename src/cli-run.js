/** CLI command implementations. */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadTasks, sampleTasks } from "./tasks.js";
import { PlatformDriver } from "./platform.js";
import { DockerDriver } from "./docker.js";
import { PiWebClient } from "./piweb.js";
import { runEval } from "./run.js";

function selectTasks(args) {
  const all = loadTasks(args.tasks);
  let tasks = sampleTasks(all, args.nTasks, args.sampleSeed);
  if (Array.isArray(args.only) && args.only.length) tasks = tasks.filter((t) => args.only.includes(t.id));
  return { all, tasks };
}

function buildDriver(args) {
  if (args.driver === "docker") return new DockerDriver();
  const url = args.platformUrl ?? process.env.PLATFORM_URL;
  const key = args.platformKey ?? process.env.PLATFORM_KEY;
  if (!url || !key) throw new Error("platform driver needs --platform-url/--platform-key (or PLATFORM_URL/PLATFORM_KEY)");
  return new PlatformDriver({ url, key, imageMap: args.imageMap ?? {} });
}

function buildPiWeb(args) {
  const url = args.piwebUrl ?? process.env.PIWEB_URL;
  const key = args.piwebKey ?? process.env.PIWEB_KEY;
  if (!url || !key) throw new Error("need --piweb-url/--piweb-key (or PIWEB_URL/PIWEB_KEY)");
  return new PiWebClient({ url, key });
}

function parseModel(m) {
  if (!m) return undefined;
  const idx = m.indexOf("/");
  if (idx <= 0) throw new Error(`--model expects provider/modelId, got "${m}"`);
  return { provider: m.slice(0, idx), modelId: m.slice(idx + 1) };
}

export async function listCommand(args) {
  if (!args.tasks) throw new Error("--tasks <dir> required");
  const { all, tasks } = selectTasks(args);
  console.log(`total: ${all.length}, selected: ${tasks.length}${args.nTasks ? ` (--n-tasks ${args.nTasks} --sample-seed ${args.sampleSeed ?? 0})` : ""}`);
  for (const t of tasks) {
    console.log(`${t.id}\t${t.dockerImage}\ttimeout=${Math.round(t.agentTimeoutSec / 60)}m`);
  }
}

export async function runCommand(args) {
  if (!args.tasks) throw new Error("--tasks <dir> required");
  const driver = buildDriver(args);
  const piweb = buildPiWeb(args);
  const { runDir, failures } = await runEval({
    tasksRoot: args.tasks,
    driver,
    piweb,
    model: parseModel(args.model),
    runId: args.runId ?? new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19),
    jobsDir: args.jobsDir ?? "jobs",
    concurrency: args.concurrency,
    nTasks: args.nTasks,
    sampleSeed: args.sampleSeed,
    toolNames: Array.isArray(args.toolNames) ? args.toolNames : undefined,
    keepContainers: Boolean(args.keepContainers),
    autoResume: !args.noAutoResume,
    onlyTasks: Array.isArray(args.only) ? args.only : [],
    ...(args.cpu ? { cpuOverride: Number(args.cpu) } : {}),
    ...(args.memoryMb ? { memoryOverride: Number(args.memoryMb) } : {}),
  });
  console.log(`\nreport: ${join(runDir, "report.md")}`);
  if (failures.length) {
    console.log(`${failures.length} task(s) failed to run — see state.json`);
    process.exitCode = 2;
  }
}

export async function sifCommand(args) {
  if (!args.tasks || !args.outDir) throw new Error("--tasks <dir> --out-dir <dir> required");
  const { tasks } = selectTasks(args);
  const lines = [
    "#!/usr/bin/env bash",
    "# Generated by eval-runner (deepswe convert-sif).",
    "# Converts deep-swe task images (docker, public.ecr.aws) to SIF for the",
    "# sandbox platform. Run ON THE LINUX HOST with apptainer installed.",
    "# Disk note: SIF files do NOT share layers — plan for the SUM of full image",
    "# sizes (plus ~2x temp during conversion). Register each SIF in the platform",
    "# Admin console (or POST /api/v1/images) named EXACTLY as the docker_image",
    "# ref below, unless you pass --image-map to the runner.",
    "set -euo pipefail",
    `OUT="\${1:-${args.outDir}}"`,
    'mkdir -p "$OUT"',
    "",
  ];
  for (const t of tasks) {
    const sif = `${t.id}.sif`;
    lines.push(
      `# ${t.id} (${t.dockerImage})`,
      `if [ ! -f "$OUT/${sif}" ]; then`,
      `  apptainer build --fix-perms "$OUT/${sif}" docker://${t.dockerImage}`,
      `  # post-conversion sanity check:`,
      `  apptainer exec "$OUT/${sif}" sh -c 'git --version && ls ${t.appDir} >/dev/null && echo OK ${t.id}'`,
      `fi`,
      "",
    );
  }
  lines.push('echo "done: $(ls "$OUT" | wc -l) SIF file(s) in $OUT"');
  const script = lines.join("\n");
  if (args.out) {
    writeFileSync(args.out, script);
    console.log(`wrote ${args.out} (${tasks.length} tasks)`);
  } else {
    console.log(script);
  }
}

export async function reportCommand(args) {
  if (!args.job) throw new Error("--job <dir> required");
  // report.md is regenerated from state.json on every run; for a standalone
  // re-render we re-run runEval's report step against the existing state.
  const { writeReportFromState } = await import("./report.js");
  writeReportFromState(args.job);
  console.log(`report: ${join(args.job, "report.md")}`);
}
